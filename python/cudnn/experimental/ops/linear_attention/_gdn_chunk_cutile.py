def _array_numel(arr):
    # Total element count of a (possibly multi-dim) cuTile Array, computed as
    # s0*s1*...*s{nd-1}. `arr.ndim` is a static Python int and `arr.shape[i]`
    # requires a *constant* index during tracing, so we statically unroll over
    # the (small, <=5) rank rather than iterating `arr.shape` -- a Python `for`
    # over the shape tuple is captured by the tracer as a device loop, which
    # cuTile rejects ("Expected a range object"). K<=256 bounds the rank here.
    s = arr.shape
    nd = arr.ndim
    n = s[0]
    if nd > 1:
        n = n * s[1]
    if nd > 2:
        n = n * s[2]
    if nd > 3:
        n = n * s[3]
    if nd > 4:
        n = n * s[4]
    return n


# Bounds-checked flat access. The original kernels called
