    for i in range(48 + 2, min(64, T - i_t * BT)):
        row_off = A_base + (i_t * BT + i) * (H * BT) + o_i + 48
        b_a_44 = -ct.astype(ct.gather(A, row_off, check_bounds=False, padding_value=0.0), ct.float32)
