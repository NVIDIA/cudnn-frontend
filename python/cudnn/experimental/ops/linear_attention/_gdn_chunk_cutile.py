# Host wrappers (compute grid + fixed tile sizes, then ct.launch)
# ===========================================================================
# cuTile kernels never receive None; where the Triton path passed an optional
# tensor we pass a 1-element dummy tensor + an integer flag (USE_* / IS_VARLEN /
# HAS_*). Autotune is replaced with fixed, reasonable tile sizes.


def _dummy(device, dtype=torch.float32):
    return torch.zeros(1, device=device, dtype=dtype)


def _i32(t):
    return t if t.dtype == torch.int32 else t.to(torch.int32)


def _opt(t, device, dtype=torch.float32):
    """Resolve an optional tensor argument to a non-null cuTile launch arg:
    the contiguous tensor if present, else a 1-element dummy (paired with a
    USE_*/IS_VARLEN/HAS_* integer flag). cuTile never accepts None in launch
    args, so this is the required dummy-tensor-plus-flag pattern."""
    if t is None:
        return _dummy(device, dtype)
    return t.contiguous()


def _opt_i32(t, device):
    if t is None:
        return _dummy(device, torch.int32)
    return _i32(t)


