# ===========================================================================
# fla.ops.utils.cumsum (scalar chunk_local_cumsum, used for the gate g)
# ===========================================================================
# GATHER RATIONALE: single-pass strided (stride H) length-T vector; read once,
# cumsum'd, written back. s/o are passed flattened (1-D) by the host wrapper.


@ct.kernel
def chunk_local_cumsum_scalar_kernel(
    s,
    o,
    scale,
    cu_seqlens,
    chunk_indices,
    T,
    H: ConstInt,
    BT: ConstInt,
    REVERSE: ConstInt,
    HAS_SCALE: ConstInt,
    IS_VARLEN: ConstInt,
    HEAD_FIRST: ConstInt,
):
    i_t = ct.bid(0)
    i_bh = ct.bid(1)
    i_b = i_bh // H
    i_h = i_bh % H

    bos = i_b * T
    T_eff = T
    if IS_VARLEN:
        i_n = ct.load(chunk_indices, (i_t, 0), shape=()).item()
        i_t = ct.load(chunk_indices, (i_t, 1), shape=()).item()
        bos = ct.load(cu_seqlens, (i_n,), shape=()).item()
        eos = ct.load(cu_seqlens, (i_n + 1,), shape=()).item()
        T_eff = eos - bos

    offs = ct.arange(BT, dtype=ct.int32)
    row = i_t * BT + offs
    mask = row < T_eff
    # s/o are (B, T, H). Non-head-first is a clean multi-dim (batch, time, head)
    # access. HEAD_FIRST is a transposed (head-major) access into the same
    # buffer -- not a clean (B,T,H) block -- so it is addressed via raw element
    # offsets (mirrors the Triton stride-1 block ptr at s + i_h*T); unused on the
    # gated-delta-rule path (head_first is always False there).
    if IS_VARLEN:
        bt_batch = 0
        t_idx = bos + row
    else:
        bt_batch = i_b
        t_idx = row

    if HEAD_FIRST:
        idx = bos * H + i_h * T_eff + row
        b_s = ct.astype(s.get_raw_memory().load_offset(idx, mask=mask, padding_value=0.0), ct.float32)
    else:
        b_s = ct.astype(
            ct.gather(s, (bt_batch, t_idx, i_h), mask=mask, check_bounds=False, padding_value=0.0), ct.float32
        )
    b_o = ct.cumsum(b_s, axis=0)
    if REVERSE:
        b_z = ct.sum(b_s, axis=0)
        b_o = -b_o + b_z + b_s
    if HAS_SCALE:
        b_o = b_o * scale
    if HEAD_FIRST:
        o.get_raw_memory().store_offset(idx, ct.astype(b_o, o.dtype), mask=mask)
    else:
        ct.scatter(o, (bt_batch, t_idx, i_h), ct.astype(b_o, o.dtype), mask=mask, check_bounds=False)


