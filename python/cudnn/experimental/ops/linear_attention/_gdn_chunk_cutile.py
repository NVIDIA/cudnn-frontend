@ct.kernel
def chunk_bwd_kernel_dv_local(
    q,
    k,
    g,
    g_gamma,
    A,
    do,
    dv,
    cu_seqlens,
    chunk_indices,
    scale,
    T,
    H: ConstInt,
    HV: ConstInt,
    K: ConstInt,
    V: ConstInt,
    BT: ConstInt,
    BK: ConstInt,
    BV: ConstInt,
    USE_G: ConstInt,
    USE_G_GAMMA: ConstInt,
    USE_A: ConstInt,
    IS_VARLEN: ConstInt,
):
    i_t = ct.bid(0)
    i_bh = ct.bid(1)
    i_b = i_bh // HV
    i_h = i_bh % HV

    qf = q.get_raw_memory()
    kf = k.get_raw_memory()
    dof = do.get_raw_memory()
    dvf = dv.get_raw_memory()
    Af = A.get_raw_memory()
    gf = g.get_raw_memory()

    if IS_VARLEN:
        i_n = ct.load(chunk_indices, (i_t, 0), shape=()).item()
        i_t = ct.load(chunk_indices, (i_t, 1), shape=()).item()
        bos = ct.load(cu_seqlens, (i_n,), shape=()).item()
        eos = ct.load(cu_seqlens, (i_n + 1,), shape=()).item()
        T = eos - bos
    else:
        bos = i_b * T

    q_base = (bos * H + i_h // (HV // H)) * K
    k_base = (bos * H + i_h // (HV // H)) * K
    do_base = (bos * HV + i_h) * V
    dv_base = (bos * HV + i_h) * V

    r_bt = ct.arange(BT, dtype=ct.int32)
    r_bk = ct.arange(BK, dtype=ct.int32)
    r_bv = ct.arange(BV, dtype=ct.int32)

    o_t = i_t * BT + r_bt
    m_t = o_t < T

    b_A = ct.zeros((BT, BT), dtype=ct.float32)
    b_g = ct.zeros((BT,), dtype=ct.float32)
    b_gamma = 0.0

    if USE_A:
        A_base = (bos * HV + i_h) * BT
        a_row = r_bt
        a_col = i_t * BT + r_bt
        A_off = A_base + a_row[:, None] * 1 + a_col[None, :] * (HV * BT)
        A_mask = (a_row[:, None] < BT) & (a_col[None, :] < T)
        b_A = gather_flat(Af, A_off, mask=A_mask, padding_value=0)
    else:
        if USE_G:
            g_base = bos * HV + i_h
            g_off = g_base + o_t * HV
            b_g = gather_flat(gf, g_off, mask=m_t, padding_value=0)
        if USE_G_GAMMA:
            b_gamma = ct.load(g_gamma, (i_h,), shape=()).item()
            b_g = b_gamma * ct.astype(r_bt + 1, ct.float32)

        for i_k in range(ct.cdiv(K, BK)):
            k_col = i_k * BK + r_bk
            q_t = i_t * BT + r_bt
            q_off = q_base + k_col[:, None] * 1 + q_t[None, :] * (H * K)
            q_mask = (k_col[:, None] < K) & (q_t[None, :] < T)
            b_q = gather_flat(qf, q_off, mask=q_mask, padding_value=0)
            k_row = i_t * BT + r_bt
            k_off = k_base + k_row[:, None] * (H * K) + k_col[None, :]
            k_mask = (k_row[:, None] < T) & (k_col[None, :] < K)
            b_k = gather_flat(kf, k_off, mask=k_mask, padding_value=0)
            b_A = b_A + safe_dot(b_k, b_q) * scale

        if USE_G or USE_G_GAMMA:
            if H <= 16:
                b_g_ref = ct.max(b_g, axis=0)
                b_A = b_A * (exp2(b_g[None, :] - b_g_ref) * exp2(b_g_ref - b_g[:, None]))
            elif USE_G:
                g_base = bos * HV + i_h
                b_g_ref = ct.astype(gf.load_offset(g_base + i_t * BT * HV).item(), ct.float32)
                b_A = b_A * (exp2(b_g[None, :] - b_g_ref) * exp2(b_g_ref - b_g[:, None]))
            else:
                b_g_ref = b_gamma
                b_A = b_A * (exp2(b_g[None, :] - b_g_ref) * exp2(b_g_ref - b_g[:, None]))

    m_A = (o_t[:, None] <= o_t[None, :]) & (m_t[:, None] & m_t[None, :])
    b_A = ct.astype(ct.where(m_A, b_A, ct.zeros((BT, BT), dtype=ct.float32)), do.dtype)

    for i_v in range(ct.cdiv(V, BV)):
        v_idx = i_v * BV + r_bv
        do_row = i_t * BT + r_bt
        do_off = do_base + do_row[:, None] * (HV * V) + v_idx[None, :]
        do_mask = (do_row[:, None] < T) & (v_idx[None, :] < V)
        b_do = gather_flat(dof, do_off, mask=do_mask, padding_value=0)
        b_dv = safe_dot(ct.astype(b_A, b_do.dtype), b_do)
        dv_off = dv_base + do_row[:, None] * (HV * V) + v_idx[None, :]
        scatter_flat(dvf, dv_off, ct.astype(b_dv, dv.dtype), mask=do_mask)


@ct.kernel
def chunk_bwd_kernel_dv_local_rows(
    q,
    k,
    g,
    do,
    dv,
    scale,
    T,
    H: ConstInt,
    HV: ConstInt,
    K: ConstInt,
    V: ConstInt,
    BT: ConstInt,
    BR: ConstInt,
    BK: ConstInt,
    BV: ConstInt,
    USE_G: ConstInt,
):
    i_r = ct.bid(0)
    i_t = ct.bid(1)
    i_bh = ct.bid(2)
    i_b = i_bh // HV
    i_h = i_bh % HV
    bos = i_b * T

    qf = q.get_raw_memory()
    kf = k.get_raw_memory()
    dof = do.get_raw_memory()
    dvf = dv.get_raw_memory()
    gf = g.get_raw_memory()

    q_base = (bos * H + i_h // (HV // H)) * K
    k_base = (bos * H + i_h // (HV // H)) * K
    do_base = (bos * HV + i_h) * V
    dv_base = (bos * HV + i_h) * V
    g_base = bos * HV + i_h

    r_br = ct.arange(BR, dtype=ct.int32)
    r_bt = ct.arange(BT, dtype=ct.int32)
    r_bk = ct.arange(BK, dtype=ct.int32)
    r_bv = ct.arange(BV, dtype=ct.int32)

    o_r = i_r * BR + r_br
    o_t = r_bt

    b_A = ct.zeros((BR, BT), dtype=ct.float32)
    for i_k in range(ct.cdiv(K, BK)):
        k_col = i_k * BK + r_bk
        k_row = i_t * BT + i_r * BR + r_br
        k_off = k_base + k_row[:, None] * (H * K) + k_col[None, :]
        k_mask = (k_row[:, None] < T) & (k_col[None, :] < K)
        b_k = gather_flat(kf, k_off, mask=k_mask, padding_value=0)
        q_t = i_t * BT + r_bt
        q_off = q_base + k_col[:, None] * 1 + q_t[None, :] * (H * K)
        q_mask = (k_col[:, None] < K) & (q_t[None, :] < T)
        b_q = gather_flat(qf, q_off, mask=q_mask, padding_value=0)
        b_A = b_A + safe_dot(b_k, b_q) * scale

    if USE_G:
        g_rows_idx = i_t * BT + i_r * BR + r_br
        g_rows_off = g_base + g_rows_idx * HV
        b_g_rows = gather_flat(gf, g_rows_off, mask=(g_rows_idx < T), padding_value=0)
        g_cols_idx = i_t * BT + r_bt
        g_cols_off = g_base + g_cols_idx * HV
        b_g_cols = gather_flat(gf, g_cols_off, mask=(g_cols_idx < T), padding_value=0)
        b_g_ref = ct.max(b_g_cols, axis=0)
        b_A = b_A * (exp2(b_g_cols[None, :] - b_g_ref) * exp2(b_g_ref - b_g_rows[:, None]))

    o_abs_r = i_t * BT + o_r
    o_abs_t = i_t * BT + o_t
    m_r = o_abs_r < T
    m_t = o_abs_t < T
    m_A = (o_r[:, None] <= o_t[None, :]) & (m_r[:, None] & m_t[None, :])
    b_A = ct.astype(ct.where(m_A, b_A, ct.zeros((BR, BT), dtype=ct.float32)), do.dtype)

    for i_v in range(ct.cdiv(V, BV)):
        v_idx = i_v * BV + r_bv
        do_row = i_t * BT + r_bt
        do_off = do_base + do_row[:, None] * (HV * V) + v_idx[None, :]
        do_mask = (do_row[:, None] < T) & (v_idx[None, :] < V)
        b_do = gather_flat(dof, do_off, mask=do_mask, padding_value=0)
        b_dv = safe_dot(ct.astype(b_A, b_do.dtype), b_do)
        dv_row = i_t * BT + i_r * BR + r_br
        dv_off = dv_base + dv_row[:, None] * (HV * V) + v_idx[None, :]
        dv_mask = (dv_row[:, None] < T) & (v_idx[None, :] < V)
        scatter_flat(dvf, dv_off, ct.astype(b_dv, dv.dtype), mask=dv_mask)


