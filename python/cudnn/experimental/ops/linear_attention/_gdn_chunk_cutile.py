# which cuTile 1.4.0 rejects (it requires a per-rank index tuple). The author's
# intent is 1-D flat semantics, so check_bounds=True maps to a 1-D bounds mask
# `0 <= off < numel`, AND-ed with any caller mask. Pass `numel = _array_numel(arr)`.
