def chunk_fwd_o(
    q,
    k,
    v,
    h,
    g=None,
    g_gamma=None,
    scale=None,
    state_v_first=False,
    cu_seqlens=None,
    chunk_size=64,
    chunk_indices=None,
):
    B, T, H, K, V, HV = *q.shape, v.shape[-1], v.shape[2]
    BT = chunk_size
    if chunk_indices is None and cu_seqlens is not None:
        chunk_indices = prepare_chunk_indices(cu_seqlens, BT)
    NT = _cdiv(T, BT) if cu_seqlens is None else len(chunk_indices)
    if scale is None:
        scale = k.shape[-1] ** -0.5
    o = torch.empty_like(v)
    BK = min(max(_next_power_of_2(K), 16), 64)
    BV = 64
    is_varlen = cu_seqlens is not None
    dev = q.device
    grid = (_cdiv(V, BV), NT, B * HV)
    g_arg = _opt(g, dev)
    gg_arg = _opt(g_gamma, dev)
    cu_arg = _opt_i32(cu_seqlens if is_varlen else None, dev)
    ci_arg = _opt_i32(chunk_indices if is_varlen else None, dev)
    ct.launch(
        _stream(),
        grid,
        chunk_fwd_kernel_o,
        (
            # Multi-dim arrays passed as-is: the kernel uses per-dim indices +
            # real strides, so no host-side .contiguous()/flatten is required.
            q,
            k,
            v,
            h,
            g_arg,
            gg_arg,
            o,
            cu_arg,
            ci_arg,
            float(scale),
            T,
            H,
            HV,
            K,
            V,
            BT,
            BK,
            BV,
            int(g is not None),
            int(g_gamma is not None),
            int(state_v_first),
            int(is_varlen),
        ),
    )
    return o


def chunk_bwd_dqkwg(
    q,
    k,
    v,
    do,
    h,
    dh,
    w=None,
    g=None,
    g_gamma=None,
    dv=None,
    scale=None,
    state_v_first=False,
    cu_seqlens=None,
    chunk_size=64,
    chunk_indices=None,
):
    B, T, H, K, V, HV = *k.shape, v.shape[-1], v.shape[2]
    BT = chunk_size
    if chunk_indices is None and cu_seqlens is not None:
        chunk_indices = prepare_chunk_indices(cu_seqlens, BT)
    NT = _cdiv(T, BT) if cu_seqlens is None else len(chunk_indices)
    CONST_TILING = 64
    BK = min(max(_next_power_of_2(K), 16), CONST_TILING)
    BV = min(max(_next_power_of_2(V), 16), CONST_TILING)
    NK = _cdiv(K, BK)
    dq = q.new_empty(B, T, HV, K)
    dk = k.new_empty(B, T, HV, K)
    dg = torch.empty(NK, *g.shape, dtype=torch.float32, device=g.device) if g is not None else None
    dw = torch.empty_like(w) if w is not None else None
    is_varlen = cu_seqlens is not None
    dev = q.device
    grid = (NK, NT, B * HV)
    g_arg = _opt(g, dev)
    gg_arg = _opt(g_gamma, dev)
    dw_arg = dw if dw is not None else _dummy(dev, k.dtype)
    dv_arg = _opt(dv, dev)
    dg_arg = dg if dg is not None else _dummy(dev)
    cu_arg = _opt_i32(cu_seqlens if is_varlen else None, dev)
    ci_arg = _opt_i32(chunk_indices if is_varlen else None, dev)
    use_dw = int(dw is not None and dv is not None)
    ct.launch(
        _stream(),
        grid,
        chunk_bwd_kernel_dqkwg,
        (
            q.contiguous(),
            k.contiguous(),
            v.contiguous(),
            g_arg,
            gg_arg,
            h.contiguous(),
            do.contiguous(),
            dh.contiguous(),
            dq,
            dk,
            dw_arg,
            dv_arg,
            dg_arg,
            cu_arg,
            ci_arg,
            float(scale),
            B,
            T,
            H,
            HV,
            K,
            V,
            BT,
            BK,
            BV,
            int(g is not None),
            int(g_gamma is not None),
            use_dw,
            int(state_v_first),
            int(is_varlen),
        ),
    )
    if H != HV:
        dq = dq.view(B, T, H, HV // H, K).sum(3)
        dk = dk.view(B, T, H, HV // H, K).sum(3)
    if dg is not None:
        dg = dg.sum(0)
    return dq, dk, dw, dg


