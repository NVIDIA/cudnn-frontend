@cute.jit
def kda_launch(
    mQ: cute.Tensor,
    mK: cute.Tensor,
    mV: cute.Tensor,
    mG: cute.Tensor,
    mBeta: cute.Tensor,
    mCu: cute.Tensor,
    mIS: cute.Tensor,
    mMW: cute.Tensor,
    mQG: cute.Tensor,
    mKG: cute.Tensor,
    mUT: cute.Tensor,
    mZ: cute.Tensor,
    mAv: cute.Tensor,
    mKGt: cute.Tensor,
    mUTt: cute.Tensor,
    mSS: cute.Tensor,
    mMT: cute.Tensor,
    mCT: cute.Tensor,
    mO: cute.Tensor,
    mFS: cute.Tensor,
    nseq: cutlass.Constexpr,
    nheads: cutlass.Constexpr,
    max_chunks: cutlass.Constexpr,
    nch: cutlass.Constexpr,
    nseg: cutlass.Constexpr,
    stream: cudadrv.CUstream,
):
    scale = 1.0 / math.sqrt(DIM)

    mma_p = hh.make_trivial_tiled_mma(
        BF16,
        BF16,
        cute.nvgpu.OperandMajorMode.K,
        cute.nvgpu.OperandMajorMode.K,
        F32,
        (1, 1, 1),
        tiler_mn=(64, 16),
    )
    prep_kernel(
        mQ,
        mK,
        mV,
        mG,
        mBeta,
        mCu,
        mMW,
        mQG,
        mKG,
        mUT,
        mZ,
        mAv,
        mma_p,
        scale,
        nch,
    ).launch(grid=[max_chunks, nseq, nheads], block=[128, 1, 1], stream=stream)

    mma_s = hh.make_trivial_tiled_mma(
        BF16,
        BF16,
        cute.nvgpu.OperandMajorMode.K,
        cute.nvgpu.OperandMajorMode.MN,
        F32,
        (2, 1, 1),
        tiler_mn=(64, 128),
        a_source=warpgroup.OperandSource.RMEM,
    )
    mma_n = hh.make_trivial_tiled_mma(
        BF16,
        BF16,
        cute.nvgpu.OperandMajorMode.K,
        cute.nvgpu.OperandMajorMode.K,
        F32,
        (2, 1, 1),
        tiler_mn=(64, 16),
        a_source=warpgroup.OperandSource.RMEM,
    )

    sMW_1 = cute.slice_(hh.make_smem_layout_b(utils.LayoutEnum.ROW_MAJOR, (128, 16, 128), BF16, NSTAGE), (None, None, 0))
    sKG_1 = cute.slice_(hh.make_smem_layout_b(utils.LayoutEnum.COL_MAJOR, (128, 128, 16), BF16, NSTAGE), (None, None, 0))
    sZ_1 = cute.slice_(hh.make_smem_layout_b(utils.LayoutEnum.ROW_MAJOR, (128, 16, 16), BF16, NSTAGE), (None, None, 0))
    sAV_1 = cute.make_layout((1, 128), stride=(128, 1))

    op = cpasync.CopyBulkTensorTileG2SOp()
    atom_mw, tMW = cpasync.make_tiled_tma_atom(op, mMW, sMW_1, (16, 128))
    atom_qg, tQG = cpasync.make_tiled_tma_atom(op, mQG, sMW_1, (16, 128))
    atom_kg, tKG = cpasync.make_tiled_tma_atom(op, mKGt, sKG_1, (128, 16))
    atom_ut, tUT = cpasync.make_tiled_tma_atom(op, mUTt, sKG_1, (128, 16))
    atom_z, tZ = cpasync.make_tiled_tma_atom(op, mZ, sZ_1, (16, 16))
    atom_av, tAV = cpasync.make_tiled_tma_atom(op, mAv, sAV_1, (1, 128))

    if cutlass.const_expr(nseg > 1):
        for md in cutlass.range_constexpr(2):
            seg_kernel(
                mCu,
                mIS,
                mO,
                mFS,
                mSS,
                mMT,
                mCT,
                atom_mw,
                tMW,
                atom_qg,
                tQG,
                atom_kg,
                tKG,
                atom_ut,
                tUT,
                atom_z,
                tZ,
                atom_av,
                tAV,
                mma_s,
                mma_n,
                nch,
                nheads,
                nseg,
                md,
            ).launch(grid=[nseg, nheads, nseq], block=[256, 1, 1], stream=stream)

        mma_c = hh.make_trivial_tiled_mma(
            BF16,
            BF16,
            cute.nvgpu.OperandMajorMode.K,
            cute.nvgpu.OperandMajorMode.MN,
            F32,
            (2, 1, 1),
            tiler_mn=(64, 128),
            a_source=warpgroup.OperandSource.RMEM,
        )
        comb_kernel(
            mIS,
            mSS,
            mMT,
            mCT,
            mma_c,
            nheads,
            nseg,
        ).launch(grid=[nseq, nheads, 1], block=[256, 1, 1], stream=stream)

    seg_kernel(
        mCu,
        mIS,
        mO,
        mFS,
        mSS,
        mMT,
        mCT,
        atom_mw,
        tMW,
        atom_qg,
        tQG,
        atom_kg,
        tKG,
        atom_ut,
        tUT,
        atom_z,
        tZ,
        atom_av,
        tAV,
        mma_s,
        mma_n,
        nch,
        nheads,
        nseg,
        2,
    ).launch(grid=[nseg, nheads, nseq], block=[256, 1, 1], stream=stream)


_CACHE = {}
_WS = {}


def _pick_nseg(T, N, H):
    L = T // max(N, 1)
    ncs = (L + 15) // 16
    p = min(132 // (N * H), ncs // 4, 8)
    if p < 3:
        return 1
    return p


def _ws(nch, H, N, nseg, device):
    key = (nch, H, N, nseg, str(device))
    w = _WS.get(key)
    if w is None:
        c = nch * H
        kg = torch.empty((c * 16, 128), dtype=torch.bfloat16, device=device)
        ut = torch.empty((c * 16, 128), dtype=torch.bfloat16, device=device)
        nop = max(N * H * nseg, 1)
        w = (
            torch.empty((c * 16, 128), dtype=torch.bfloat16, device=device),
            torch.empty((c * 16, 128), dtype=torch.bfloat16, device=device),
            kg,
            ut,
            torch.empty((c * 16, 16), dtype=torch.bfloat16, device=device),
            torch.empty((c, 128), dtype=torch.float32, device=device),
            kg.t(),
            ut.t(),
            torch.empty((nop, 128, 128), dtype=torch.float32, device=device),
            torch.empty((nop, 128, 128), dtype=torch.bfloat16, device=device),
            torch.empty((nop, 128, 128), dtype=torch.float32, device=device),
        )
        _WS[key] = w
    return w


def run(q, k, v, g, beta, cu_seqlens, initial_state, o, final_state):
    T, H, D = q.shape
    N = initial_state.shape[0]
    nch = T // 16 + N + 1
    max_chunks = (T + 15) // 16
    nseg = _pick_nseg(T, N, H)

    mw, qg, kg, ut, z, av, kgt, utt, ss, mt, ct = _ws(nch, H, N, nseg, q.device)

    key = (T, H, N, D)
    fn = _CACHE.get(key)
    stream = cudadrv.CUstream(torch.cuda.current_stream().cuda_stream)

    def _t(x):
        return from_dlpack(x, assumed_align=16)

    args = (
        _t(q),
        _t(k),
        _t(v),
        _t(g),
        _t(beta),
        from_dlpack(cu_seqlens, assumed_align=4),
        _t(initial_state),
        _t(mw),
        _t(qg),
        _t(kg),
        _t(ut),
        _t(z),
        _t(av),
        _t(kgt),
        _t(utt),
        _t(ss),
        _t(mt),
        _t(ct),
        _t(o),
        _t(final_state),
    )
    if fn is None:
        fn = cute.compile(kda_launch, *args, N, H, max_chunks, nch, nseg, stream)
        _CACHE[key] = fn
    fn(*args, stream)
