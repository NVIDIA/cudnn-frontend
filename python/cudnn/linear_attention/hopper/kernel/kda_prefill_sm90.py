BF16 = cutlass.BFloat16
F32 = cutlass.Float32
I32 = cutlass.Int32

LOG2E = 1.4426950408889634
DIM = 128
NSTAGE = 6
NSTC = 3
VSPLIT = 8
TXBYTES = 4 * (16 * 128 * 2) + 16 * 16 * 2 + 128 * 4


def c2a_layout(c, a):
    return cute.make_layout(
        (a, c.shape[1], (c.shape[2], cute.size(c, mode=[0]) // cute.size(a))),
        stride=(
            c.stride[0],
            c.stride[1],
            (c.stride[2], cute.size(a, mode=[2]) * c.stride[0][2]),
        ),
    )


@cute.jit
def acc_to_a(acc, a_shape):
    operand = cute.make_rmem_tensor_like(c2a_layout(acc.layout, a_shape), BF16)
    as_acc = cute.make_tensor(operand.iterator, acc.layout)
    as_acc.store(acc.load().to(BF16))
    return operand


@cute.jit
def bf16_c_to_a(frag, a_shape):
    """Alias a packed BF16 WGMMA-C fragment as an RMEM A operand."""
    return cute.make_tensor(frag.iterator, c2a_layout(frag.layout, a_shape))


