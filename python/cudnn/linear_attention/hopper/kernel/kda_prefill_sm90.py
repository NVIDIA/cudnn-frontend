"""Kimi Delta Attention (KDA) chunked linear-attention prefill for Hopper (sm90).

PREP (grid = (gap-safe_global_chunks, H), 128 thr) -- fully parallel over
16-token chunks.  A CTA maps its virtual packed-chunk coordinate through
cu_seqlens, so uneven and zero-length batches do not require an N-times
max-sequence launch bound.  Per chunk it builds the pieces of the affine operator
in UT/WY form.  BT = 16 plus "every exponent that reaches exp2 is <= 0" keeps
the production gate (g in (-5,0), mean -2.5) inside fp32 range:

    G   = chunk-local inclusive cumsum of g            (<= 0, decreasing)
    E   = exp(G) in (0,1] ,  a = E[L-1]
    kw  = k * E                                        (<= |k|)
    ub  = beta * k / E                                 (<= e^{|G_L|})
    kg  = ub * a = beta*k*exp(G_L - G)                 (<= |k|)
    qg  = scale * q * E
    T   = I + strict_lower(kw @ ub^T) ,  Z = tril(qg @ ub^T, 0)
    wt  = T^{-1} kw ,  ut = T^{-1} v                   (forward substitution)

SCAN (grid = (N, H), 256 thr = 2 warpgroups) -- sequential over chunks with the
state kept TRANSPOSED as an fp32 wgmma accumulator St = S^T [Dv=128, Dk=128],
which is exactly the V-major layout of initial_state / final_state:

    Rt  = ut^T + St @ (-wt)^T      (M=128, N=16,  K=128)
    Ot  = St @ qg^T                (M=128, N=16,  K=128)
    Ot += Rt @ Z^T                 (M=128, N=16,  K=16)
    St  = St*a + Rt @ kg           (M=128, N=128, K=16)

Transposing the state makes every wgmma full-M (128 rows) instead of the 16-row
shape the untransposed recurrence would give.  Both St and Rt are fed to WGMMA
as REGISTER A-operands (OperandSource.RMEM), so the [128,128] state never moves
through shared memory -- that removes ~96 KB of SMEM traffic and two CTA
barriers from every step of the serial chain.

Provenance
----------
Generated by a Kernel Factory campaign on the ``kda_chunked_prefill_sm90``
operation (campaign ``m58kq4q63h0zn893p6sxywe9g4``, kernel
``4e60c30a6b60c3d3140f59e25e65aa265ebcba7fae8531eabdef728083d87ad1``,
solution ``kda_sm90_runtime_partial_tail_v64``).

Verified on H100 80GB HBM3 (SXM) at the production gate
(``gate_lower_bound = -5``) with a non-zero ``initial_state``, geomean over ten
shapes, two independent passes:

===================  ===========  ==========  ==========
metric               this kernel  FlashKDA    ratio
===================  ===========  ==========  ==========
per-call             368.5 us     438.7 us    1.19x
pipelined            257.5 us     398.2 us    1.54x
===================  ===========  ==========  ==========

Accuracy against an fp64 oracle is 5.0e-03 to 1.0e-02, against FlashKDA's own
7.5e-03 to 1.0e-02 on the same inputs.

The predecessor vendored here used ``BT = 64`` with a single mid-chunk anchor and
returned 100% NaN at ``gate_lower_bound = -5``: a 64-token chunk spans ~118 in
the exponent there and fp32 overflows at 88. Per-sub-block anchoring cannot fix
that, because KDA's decay is per-key-channel, so the cross-block correction
``exp(r_j[d] - r_i[d])`` lives inside the channel sum of ``Wn @ U^T`` and no
post-matmul scalar removes it. Every token in one matmul must share an anchor,
which forces ``BT <= 16``. This kernel goes further and arranges for every
exponent reaching ``exp2`` to be ``<= 0``, so the exponential can only underflow
to zero -- overflow is structurally impossible rather than merely budgeted.
"""

