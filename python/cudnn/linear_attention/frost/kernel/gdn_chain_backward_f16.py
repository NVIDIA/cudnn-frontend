def build_configs(
    bprop_module,
    io_dtype,
    summary_dtype,
    transition_dtype,
    series_dtype,
    *,
    fused_h_m,
    series,
    coarse,
    compact_qdo,
    use_dstate0,
    fused_l2norm,
    num_sm,
    log_gate,
    safe_gate,
    beta_sigmoid,
    allow_neg_eigval,
    d_k,
    d_v,
    expand_num,
    k_slots,
    v_slots,
    beta_slots,
):
    tinv_cfg = gdn_tinv_f16.build_cfg(
        io_dtype,
        num_sm=num_sm,
        log_gate=log_gate,
        safe_gate=safe_gate,
        beta_sigmoid=beta_sigmoid,
        allow_neg_eigval=allow_neg_eigval,
        d_k=d_k,
        expand_num=expand_num,
        k_slots=k_slots,
        beta_slots=beta_slots,
    )
    summary_cfg = None
    transition_cfg = None
    if fused_h_m:
        summary_cfg = gdn_summary_f16.build_cfg(
            io_dtype,
            summary_dtype,
            max_active_clusters=num_sm,
            use_initial_state=False,
            log_gate=log_gate,
            safe_gate=safe_gate,
            d_k=d_k,
            d_v=d_v,
            expand_num=expand_num,
            k_slots=k_slots,
            v_slots=v_slots,
        )
    else:
        transition_cfg = gdn_recompute_f16.build_cfg(
            io_dtype,
            transition_dtype,
            max_active_clusters=num_sm,
            use_initial_state=False,
            store_final_state=True,
            enable_checkpoints=False,
            seed_checkpoints=False,
            log_gate=log_gate,
            safe_gate=safe_gate,
            seed_identity=True,
            v_is_zero=True,
            d_k=d_k,
            d_v=d_k,
            expand_num=expand_num,
            k_slots=k_slots,
            v_slots=v_slots,
        )
    series_cfg = None
    if series:
        series_cfg = gdn_recompute_f16.build_cfg(
            io_dtype,
            series_dtype,
            max_active_clusters=num_sm,
            use_initial_state=not coarse,
            store_final_state=False,
            enable_checkpoints=True,
            seed_checkpoints=coarse,
            log_gate=log_gate,
            safe_gate=safe_gate,
            d_k=d_k,
            d_v=d_v,
            expand_num=expand_num,
            k_slots=k_slots,
            v_slots=v_slots,
        )
    bwd_summary_cfg = gdn_bprop_summary_f16.build_cfg(
        io_dtype,
        max_active_clusters=num_sm,
        use_dstate_in=False,
        log_gate=log_gate,
        safe_gate=safe_gate,
        d_k=d_k,
        d_v=d_v,
        expand_num=expand_num,
        k_slots=k_slots,
    )
    bprop_cfg = bprop_module.build_cfg(
        io_dtype,
        max_active_clusters=num_sm,
        use_initial_state=True,
        use_dstate_in=True,
        use_dstate0=use_dstate0,
        log_gate=log_gate,
        safe_gate=safe_gate,
        beta_sigmoid=beta_sigmoid,
        allow_neg_eigval=allow_neg_eigval,
        fused_l2norm=fused_l2norm,
        d_k=d_k,
        d_v=d_v,
        expand_num=expand_num,
        **({} if compact_qdo else dict(tinv_source="gmem")),
        k_slots=k_slots,
        v_slots=v_slots,
        beta_slots=beta_slots,
    )
    return tinv_cfg, summary_cfg, transition_cfg, series_cfg, bwd_summary_cfg, bprop_cfg


